#!/usr/bin/env python3
"""Import individually reviewed Cozy V2 artwork into the Expo repository.

Usage:
    python3 scripts/import-cozy-graphics.py /path/to/cozy-production-assets-v2.zip
    python3 scripts/import-cozy-graphics.py /path/to/cozy-production-assets-v2.zip --apply

Dry-run by default. This script does not build an APK or modify gameplay.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import shutil
import zipfile

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "assets" / "cozy-redesign" / "illustrations"
TYPES = {".png", ".webp", ".jpg", ".jpeg"}
EXPECTED_FOLDERS = {"characters", "decorations", "ui", "cards", "backgrounds", "effects"}

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("zip_path", type=Path)
    parser.add_argument("--apply", action="store_true", help="Copy validated assets to the repository")
    args = parser.parse_args()
    if not args.zip_path.is_file():
        parser.error(f"ZIP not found: {args.zip_path}")

    with zipfile.ZipFile(args.zip_path) as archive:
        names = set(archive.namelist())
        if "asset-manifest.json" not in names:
            raise SystemExit("Missing expected asset-manifest.json")
        manifest = json.loads(archive.read("asset-manifest.json"))
        if len(manifest) < 70:
            raise SystemExit("Expected at least 70 individual art entries")
        digest_map = {}
        selected = []
        seen = set()
        for item in manifest:
            name = str(item["file"])
            rel = PurePosixPath(name)
            if (rel.is_absolute() or ".." in rel.parts or len(rel.parts) < 2 or
                rel.parts[0] not in EXPECTED_FOLDERS or rel.suffix.lower() not in TYPES):
                raise SystemExit(f"Unsafe or unsupported asset path: {name}")
            if name in seen:
                raise SystemExit(f"Duplicate asset path: {name}")
            seen.add(name)
            if name not in names:
                raise SystemExit(f"Missing source asset: {name}")
            content = archive.read(name)
            if not content or len(content) > 10_000_000:
                raise SystemExit(f"Empty or oversized asset: {name}")
            suffix = rel.suffix.lower()
            if suffix == ".webp" and not (content.startswith(b"RIFF") and content[8:12] == b"WEBP"):
                raise SystemExit(f"Invalid WebP data: {name}")
            if suffix == ".png" and not content.startswith(b"\x89PNG\r\n\x1a\n"):
                raise SystemExit(f"Invalid PNG data: {name}")
            if suffix in {".jpg", ".jpeg"} and not content.startswith(b"\xff\xd8"):
                raise SystemExit(f"Invalid JPEG data: {name}")
            digest = hashlib.sha256(content).hexdigest()
            if digest != item["sha256"]:
                raise SystemExit(f"Checksum mismatch: {name}")
            digest_map[name] = digest
            selected.append((name, content))

        print(f"Verified {len(selected)} assets; {sum(len(v) for _, v in selected)/1024/1024:.1f} MiB")
        if not args.apply:
            print("Dry run; use --apply to copy assets and write an Expo require() map.")
            return

        target = TARGET.resolve()
        target.mkdir(parents=True, exist_ok=True)
        for name, content in selected:
            dst = (target / name).resolve()
            if not dst.is_relative_to(target):
                raise SystemExit(f"Invalid destination: {name}")
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(content)

        # Generate literal require calls: Metro cannot resolve dynamic image paths.
        manifest_out = ROOT / "src" / "assets" / "cozyRedesignImages.ts"
        lines = [
            "/** Generated by scripts/import-cozy-graphics.py. Do not hand-edit. */",
            "export const cozyRedesignImages = {",
        ]
        for name in sorted(digest_map):
            key = name.replace("/", "__").replace(".", "_").replace("-", "_")
            lines.append(f'  "{key}": require("../../assets/cozy-redesign/illustrations/{name}"),')
        lines.extend(["} as const;", ""])
        manifest_out.write_text("\n".join(lines), encoding="utf-8")
        print(f"Copied into {TARGET.relative_to(ROOT)}")
        print(f"Generated {manifest_out.relative_to(ROOT)}")
        print("Review sprite transparency and responsive layout before activating artwork.")
        print("No APK build was started.")

if __name__ == "__main__":
    main()
